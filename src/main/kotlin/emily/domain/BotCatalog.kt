object AudiencePreference {
    const val FEMALE = "female"
    const val MALE = "male"

    fun normalize(value: String?): String? {
        return when (value?.trim()?.lowercase(Locale.ROOT)) {
            FEMALE -> FEMALE
            MALE -> MALE
            else -> null
        }
    }
}

