data class CharacterProfile(
    val id: String,
    val audience: String = AudiencePreference.FEMALE,
    val name: String,
    val shortDescription: String,
    val selectionPhotoUrl: String,
    val welcomePhotoUrl: String,
    val welcomePhotoFileId: String? = null,
